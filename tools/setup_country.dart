#!/usr/bin/env dart
// tools/setup_country.dart
//
// Setup and build tool for Mobiz Autocare Pro.
// Note: Manual country selection is no longer required because the app
// automatically detects and switches the country based on user login.
//
// Usage: dart tools/setup_country.dart

import 'dart:io';

const _targetFile = 'lib/config/app_defaults.dart';

void _printLine([String char = '─', int width = 55]) {
  print(char * width);
}

void _printBanner() {
  _printLine('═');
  print('  🌍  Mobiz Autocare Pro — Setup & Build Tool');
  _printLine('═');
  print('');
}

String _parseVersion() {
  var appVersion = '1.6.8';
  final pubspecFile = File('pubspec.yaml');
  if (pubspecFile.existsSync()) {
    final pubspecLines = pubspecFile.readAsLinesSync();
    for (final line in pubspecLines) {
      if (line.trim().startsWith('version:')) {
        final parts = line.split(':');
        if (parts.length > 1) {
          appVersion = parts[1].trim().split('+')[0];
          break;
        }
      }
    }
  }
  return appVersion;
}

String _generateDartFile(String version) {
  return '''// AUTO-GENERATED by tools/setup_country.dart
// Note: Country selection is now automatic based on user login.

// ignore_for_file: constant_identifier_names

import 'country_config.dart';

/// Default fallback country compiled into this build.
const CountryCode kDefaultCountry = CountryCode.india;

/// Default app language fallback.
const String kDefaultLanguageCode = 'en';

/// App Version name extracted from pubspec.yaml
const String kAppVersion = '$version';
''';
}

void main() async {
  _printBanner();

  final version = _parseVersion();

  print('  ℹ️  Country selection is NO LONGER needed!');
  print('      The app automatically changes currency, phone code,');
  print('      and country settings based on user login.');
  print('');
  print('  📦  App Version : $version');
  print('  📱  APK Name    : Mobiz auto care pro v $version.apk');
  print('');

  // 1. Write lib/config/app_defaults.dart
  final outFile = File(_targetFile);
  outFile.parent.createSync(recursive: true);
  outFile.writeAsStringSync(_generateDartFile(version));
  print('  📝  Updated → $_targetFile');

  print('');
  _printLine('─');
  print('  🚀  Next steps:');
  print('       flutter run               ← run app in debug mode');
  print('       dart tools/build_apk.dart  ← build release APK directly');
  _printLine('─');
  print('');

  stdout.write('  🛠️  Would you like to build the release APK now? (y/n): ');
  final buildChoice = stdin.readLineSync()?.trim().toLowerCase() ?? '';
  if (buildChoice == 'y' || buildChoice == 'yes') {
    print('');
    print('  Starting APK build via tools/build_apk.dart...');
    print('');
    final buildProcess = await Process.start(
      'dart',
      ['tools/build_apk.dart'],
      mode: ProcessStartMode.inheritStdio,
    );
    await buildProcess.exitCode;
  }
}
